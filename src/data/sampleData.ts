const resource = (
  id: string,
  name: string,
  category: Resource['category'],
  purchaseQuantity: number,
  purchaseUnit: Unit,
  purchasePrice: number,
  yieldRate = 1,
  options: Partial<Resource> = {},
): Resource => ({
  id,
  name,
  category,
  purchaseQuantity,
  purchaseUnit,
  purchasePrice,
  yieldRate,
  usableQuantity: purchaseQuantity * yieldRate,
  storageType: 'refrigerated',
  shelfLifeDays: 7,
  minimumPurchaseLot: 1,
  priceStandard: purchasePrice,
  isReferencePrice: true,
  ...options,
})

const input = (sourceType: SourceRef['sourceType'], sourceId: string, quantity: number, unit: Unit): SourceRef => ({
  sourceType,
  sourceId,
  quantity,
  unit,
})

